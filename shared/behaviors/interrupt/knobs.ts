/**
 * 功能：她说话时怎样才算打断她（I-204，改了自己 11-19 定的规矩：明确、成句子才打断）
 *
 * 旋钮文件：能调的值都在这里。每个旋钮上面一行"用户可能怎么说"，下面可选一行"怎么调"；
 * handbook/knobs.md 那张"想改什么 → 改哪里"的表由 `node scripts/list-knobs.mjs` 从这些行生成，别手改那张表。
 *
 * 起因（2026-11-23）：语言不好打断；改成有意思的短语就打断，不是等说完整一句；不写过滤程序，按识别正确率定。
 *
 * 读法（判断在 judge.ts，纯函数）：
 *  - 她说话时，麦克风听到声音（音量、语音检测）只是"可能有人在说话"，她照常往下说；要等这段话识别出字来再判断。
 *  - 先看是不是她自己的声音从喇叭漏回麦克风（回声）：识别出的字和她正在念（或刚念完）的那段话最像的一截比，
 *    对得上的比例（1 − 最少要改几个字 ÷ 识别出的字数）至少 echoMatchRatio，就当回声，不打断、不当成你说的。
 *  - 不是回声：识别出 minChars 个字以上（中文一个字算一个，英文一个词算两个，标点不算，"嗯啊"也算字）就打断她，她停下来听你说。
 *    没有叫停词表，没有语气词过滤，不看音量和时长。
 *  - 不够字数的，不打断她，也不当成你说了一句话（不发给她、不存进聊天、不显示），只在体验记录里记一次数（带字数和对得上的比例）。
 *  - 她没在说话时，通话里（以及听她名字时）一段只有语气词的声音，如果有声不到 fillerMinVoicedSeconds 秒或最响处低于 fillerMinPeakDb，
 *    多半是杂音被认成了"嗯"，同样丢掉、只记数；又长又响的"嗯"照常当成你的回答（"嗯"在中文里常常就是"对"）。这条不是打断规则。
 *  - 有声时间按 16 kHz 的录音每 20 毫秒一格算：一格的音量超过 voicedFloor，并且超过这段最响处的 voicedPeakShare 倍，就算有声。
 * 这些都只是第一次的猜测值，没在真机上听过；体验记录里每段话的字数和比例就是用来调它们的。
 */

export interface InterruptKnobs {
  readonly minChars: number;
  readonly echoMatchRatio: number;
  readonly fillerMinVoicedSeconds: number;
  readonly fillerMinPeakDb: number;
  readonly voicedFloor: number;
  readonly voicedPeakShare: number;
}

export const INTERRUPT_KNOBS: InterruptKnobs = Object.freeze<InterruptKnobs>({
  // 用户可能怎么说：我说了好几个字她还不停 / 我就"嗯"了两声她就停了
  // 怎么调：她说话时，识别出至少几个字就打断她（中文一个字算一个，英文一个词算两个；是 3）
  minChars: 3,

  // 用户可能怎么说：她说话时麦克风把她自己的话录进去，当成我说的了 / 我说的话正好和她念的一样，她不停
  // 怎么调：识别出的字和她正在念（或刚念完）的那段话对得上的比例（0～1）到这个数就当她自己的回声；调大更不容易误丢你的话，调小更不容易被自己的回声打断。0.7：3 个字要一字不差，4～6 个字可以错 1 个，10 个字可以错 3 个（喇叭漏回来的声音常被认成同音字）
  echoMatchRatio: 0.7,

  // 用户可能怎么说：打电话时我没说话，也被认成"嗯"发给她了
  // 怎么调：她没说话时，一段只有"嗯、啊"的声音有声不到多少秒，就当杂音丢掉
  fillerMinVoicedSeconds: 0.45,

  // 用户可能怎么说：我轻轻"嗯"了一声回答她，她没收到
  // 怎么调：她没说话时，一段只有"嗯、啊"的声音最响处低于多少分贝，就当杂音丢掉；调低（比如 -36）更容易收到小声的"嗯"，但杂音也更容易混进来
  fillerMinPeakDb: -26,

  // 用户可能怎么说：（一般不用改）
  // 怎么调：算"有声"的最低音量（0～1，0.006 约 -44 dB）
  voicedFloor: 0.006,

  // 用户可能怎么说：（一般不用改）
  // 怎么调：算"有声"时还要达到这段最响处的几分之几（0.1 = 比最响处低 20 dB 以内）
  voicedPeakShare: 0.1,
});
