/**
 * 功能：聊天时头别乱晃（I-170，摇头晃脑"。我觉得在沟通状态的时候可以以一种方式限制头的移动。"）
 *
 * 旋钮文件：能调的值都在这里。每个旋钮上面一行"用户可能怎么说"，下面可选一行"怎么调"；
 * handbook/knobs.md 那张"想改什么 → 改哪里"的表由 `node scripts/list-knobs.mjs` 从这些行生成，别手改那张表。
 *
 * "在沟通"= 你在打字、她在想、在准备开口、在说或念，以及最后一次这样之后的一小段时间（linger）。这段时间里只收待机层自己给头的
 * 晃动（待机模型的头和脖子、程序小动作里头的漂移和随意歪头）；看向你、跟鼠标、害羞躲开、想事情时看别处、她回复里的点头摇头歪头、
 * 摸头的反应、身体的呼吸和轻微晃动都不动。进出都按弹簧慢慢过渡。这些都只是试用值，没在真机上看过。
 */
export interface TalkCalmKnobs {
  readonly head: number;
  readonly lingerS: number;
  readonly inS: number;
  readonly outS: number;
}

export const TALK_CALM_KNOBS: TalkCalmKnobs = Object.freeze<TalkCalmKnobs>({
  // 用户可能怎么说：聊天时她的头还是晃得厉害／聊天时她像定住了，太僵
  // 怎么调：聊天时待机的头部晃动留几成（0.3 = 三成；1 = 不收；0 = 完全不晃，不建议）
  head: 0.3,
  // 用户可能怎么说：聊完一会儿她又开始摇头晃脑了，太快／聊完好久她还一动不动
  // 怎么调：最后一次你打字、她想或她说之后，再保持安静多少秒
  lingerS: 15,
  // 用户可能怎么说：一开口她的头突然停住了，不自然
  // 怎么调：安静下来用几秒（10%～90%），越大越慢
  inS: 1.2,
  // 用户可能怎么说：聊完她的头一下子又晃起来了
  // 怎么调：晃动回来用几秒（10%～90%），越大越慢
  outS: 3,
});
