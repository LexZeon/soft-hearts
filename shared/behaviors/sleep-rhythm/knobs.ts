/**
 * 功能：她的作息：关着应用算休息、夜里那一觉更容易睡、睡得更透（I-022）
 *
 * 旋钮文件：她作息上能调的值都在这里。每个旋钮上面一行"用户可能怎么说"，下面一行"怎么调"；
 * handbook/knobs.md 那张"想改什么 → 改哪里"的表由 `node scripts/list-knobs.mjs` 从这些行生成，别手改那张表。
 * 所以这些都只是第一版的值，改一个数就生效（tests/sleep-rhythm.test.ts 有"一个旋钮"测试）。
 *
 * 读法（困倦模型本身在 shared/fatigue.ts，没换写法，这里只放作息）：
 *  - 困意积累 A：醒着按 18 小时的节奏 × 钟点倍数涨（wake：白天慢、深夜快，I-043），睡着按 3 小时消（白天睡着 3 小时消掉约 63%）。
 *    困倦 F ≈ 0.88 × A + 心情 − 刚被逗醒。钟点不再直接加困（以前有"0.12 × 凌晨那一下的钟"，2026-11-07 去掉）。
 *  - 白天的门槛（有点困 0.38 / 困 0.58 / 睡着 0.72、刚醒 0.18）这次都没动：那是 I-022 的第 3 步，等你看了效果再定。
 *  - 深夜：她最困的时刻（peakMinute）前后那一段，默认约 22:26～07:34。和"深夜不打扰""深夜提醒你休息一次"是同一段（shared/inner-loop.ts 用同一个算法）。
 *  - offline：应用关着的时候（以及你在陪别的角色、电脑睡眠时）她不在屏幕上，按"她在睡觉"算困意消退：那一刻在应用里睡着会消多快 × 这里的质量。
 *  - night：深夜你一阵子没理她时，她更容易真的睡着；深夜睡着时消得快一点，而且不自己半夜醒，等深夜过去困意够低了才醒。
 * 不变的：深夜你还醒着、30 分钟内理过她时"提醒你休息一次"照旧（这时候用的还是白天的门槛）；睡着时谁都不开口；你摸她、跟她说话、叫醒她，她照样会醒。
 */

export interface SleepRhythmKnobs {
  readonly wake: {
    readonly dayRate: number;
    readonly nightRate: number;
    readonly speedUpFrom: number;
    readonly fastFrom: number;
    readonly fastUntil: number;
    readonly slowFrom: number;
  };
  readonly offline: {
    readonly nightQuality: number;
    readonly dayQuality: number;
    readonly longestRestHours: number;
  };
  readonly night: {
    readonly peakMinute: number;
    readonly sleepEnter: number;
    readonly sleepExit: number;
    readonly quietMinutes: number;
    readonly restSpeed: number;
    readonly wakeBelow: number;
  };
}

export const SLEEP_RHYTHM_KNOBS: SleepRhythmKnobs = Object.freeze<SleepRhythmKnobs>({
  // I-043：钟点不再直接让她困，只决定醒着时困意积累涨多快。
  // 默认：白天 × 0.5，21:00 起越来越快，0 点到凌晨 5 点 × 4，5～8 点慢下来。从早上 8 点睡饱算，大约 22:20 有点困、1 点困。
  wake: {
    // 用户可能怎么说：白天她怎么老是困／白天她一点都不困、精神得不像话
    // 怎么调：白天（下面"回到白天"到"开始变快"之间）困意涨得是原来 18 小时节奏的几倍；越小白天越精神（0～10，不能是 0）
    dayRate: 0.5,
    // 用户可能怎么说：深夜她还不困／一到半夜她就困得不行
    // 怎么调：深夜（"最快"那一段）困意涨得是原来节奏的几倍；越大深夜越快困（0～10，不能是 0）
    nightRate: 4,
    // 用户可能怎么说：晚上她太早开始犯困了／晚上她困得太晚了
    // 怎么调：几点开始越来越快，单位分钟（1260 = 21:00）；从这里到下面的"最快"均匀加快
    speedUpFrom: 1260,
    // 用户可能怎么说：她最困的那段太早／太晚开始
    // 怎么调：几点起最快，单位分钟（0 = 午夜 0 点）
    fastFrom: 0,
    // 用户可能怎么说：天快亮了她还越来越困／凌晨她太早就不困了
    // 怎么调：最快的那段到几点为止，单位分钟（300 = 凌晨 5 点）；之后均匀变慢
    fastUntil: 300,
    // 用户可能怎么说：早上她还在越来越困
    // 怎么调：几点起回到白天的速度，单位分钟（480 = 早上 8 点）。四个时刻要按 回到白天→开始变快→最快→最快结束 绕一圈
    slowFrom: 480,
  },
  offline: {
    // 用户可能怎么说：关了一整晚，第二天打开她还是困／夜里才关一会儿她就一点都不困了
    // 怎么调：深夜关着的那段，按"深夜在应用里睡着"消退的快慢 × 这个数；1 = 和真睡着一样，0 = 不算休息（只能在 0～1）
    nightQuality: 1,
    // 用户可能怎么说：白天关一会儿再打开，她一下子就不困了／白天关了大半天她还是困
    // 怎么调：白天关着的那段，按"白天在应用里睡着"消退的快慢 × 这个数；0.5 = 一半时间在休息（她白天也有自己的事），1 = 整段在睡，0 = 不算（只能在 0～1）
    dayQuality: 0.5,
    // 用户可能怎么说：关了好几天再打开，她怎么还是那样／关一整夜怎么没算整夜
    // 怎么调：关着超过这么多小时，多出来的不再算休息（最多 24）；关一整夜（8～10 小时）在这之内，整夜都算。原来是 2 小时
    longestRestHours: 24,
  },
  night: {
    // 用户可能怎么说：她的夜晚整体太早了／太晚了（她几点最困）
    // 怎么调：她最困的那一刻，单位分钟（180 = 凌晨 3 点）。深夜时段从它推出来（默认约 22:26～07:34），"深夜不打扰""深夜提醒你休息"和这里的深夜一起挪
    peakMinute: 180,
    // 用户可能怎么说：深夜她一直在打瞌睡、就是不睡着／她晚上太容易睡着了
    // 怎么调：深夜你一阵子没理她时，困倦到多少她就真的入睡（白天是 0.72，不变）；越小越容易睡，要大于"困"的 0.58、不大于 0.72
    sleepEnter: 0.62,
    // 用户可能怎么说：她夜里快睡着了又醒回来，反反复复
    // 怎么调：深夜正在入睡时，困倦降到多少就不睡了（白天是 0.60）；要比上面那个小、比 0.48 大，差得越多越不反复
    sleepExit: 0.52,
    // 用户可能怎么说：我才走开一会儿她就睡着了／我都走了好久她还不睡
    // 怎么调：深夜你多久没理她（没摸、没聊、没喂、没叫醒），上面两个深夜的门槛才算数，单位分钟；30 = "深夜提醒你休息一次"认定"你还醒着"的 30 分钟，所以提醒那条照旧，别小于 30
    quietMinutes: 30,
    // 用户可能怎么说：她早上还是太困／她夜里睡一会儿就完全不困了
    // 怎么调：深夜睡着时困意消退比白天快几倍（白天睡 3 小时消掉约 63%）；1.5 = 2 小时消掉约 63%，1 = 和白天一样；关着应用的深夜也按这个算（0.5～3）
    restSpeed: 1.5,
    // 用户可能怎么说：她半夜自己醒了／她早上醒得太晚、睡得太多了
    // 怎么调：深夜里困意积累降到多少她会自己醒（白天是 0.18）；0 = 深夜不自己醒，等深夜过去、困意够低了再醒（0～0.18）。你摸她、跟她说话照样会醒
    wakeBelow: 0,
  },
});
