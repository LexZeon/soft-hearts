/**
 * 功能：她认得你常放的歌（I-077 第 2 步：歌的指纹，只存几个数；记录 docs/claude/2026-11-11-i077-step2.md）
 *
 * 旋钮文件：能调的值都在这里。每个旋钮上面一行"用户可能怎么说"，下面可选一行"怎么调"；
 * handbook/knobs.md 那张表由 `node scripts/list-knobs.mjs` 生成，别手改。
 *
 * 一首歌的指纹是前奏那十来秒的几个数（速度、三个频带的比例、亮度、弹的还是拉长的、鼓点密度）加上头几个乐段的长度，
 * 不存声音、不存歌名，存在本机的配置目录里（每个角色一份），可以清除，不随角色卡导出，不发给任何人。
 * 认歌要求放过好几遍，而且离第二像的歌足够远；宁可认不出，也不要认错。
 * 写死的只有：数的个数和范围、存多少首（防止文件越来越大）。其他都是可调的试用值，没在真歌上看过。
 */
export const SONG_MEMORY_KNOBS = Object.freeze({
  recognition: Object.freeze({
    // 用户可能怎么说：她老听不出我常放的歌／她把另一首当成了常放的那首
    // 怎么调：minPlays＝一首歌要听过几遍才可能被认出来（存了几遍的指纹才算；3＝第四遍起认得）；introSeconds＝从声音响起开始（跳过 skipSeconds 之后），听多少秒的前奏就拿来认（越长越准、越晚认出来）；skipSeconds＝开头先跳过几秒（淡入、静音）；tempoWaitSeconds＝前奏听完后，还最多等几秒让拍子锁上（速度是指纹的一部分；一直没有拍子的歌就不带速度去认）
    minPlays: 3,
    tempoWaitSeconds: 4,
    introSeconds: 10,
    skipSeconds: 1.5,
    // 怎么调：下面是"两首歌差多少还算同一首"：bpm 的比例（0.025＝差 2.5% 以内），三个频带比例的总差，亮度、弹的程度、鼓点密度（相对）；调小 = 认得更严
    bpmRatio: 0.025,
    bands: 0.1,
    bright: 0.12,
    pluck: 0.18,
    density: 0.2,
    // 怎么调：第二像的歌的差距要比最像的至少大这么多倍（margin）才认；整体差距要在 limit 以内（1＝每项都刚好在上面的范围里）才认
    margin: 1.5,
    limit: 1,
    // 怎么调：任何一项单独差到这么多倍的范围（worst）就不认，哪怕别的项都很像（比如同一首歌快了 4%，是另一个版本，不是同一首）
    worst: 1.6,
  }),
  keep: Object.freeze({
    // 用户可能怎么说：她记得的歌太多了／认得的歌老是忘
    // 怎么调：最多存多少首（超了先丢听得最少、最久没听的）；只听过一遍、超过 staleDays 天没再听到的指纹会被清掉；一首歌要放满 minHeardSeconds 秒才记
    maxSongs: 80,
    staleDays: 45,
    minHeardSeconds: 30,
    // 怎么调：同一首歌多次的平均里，旧的次数最多算几遍（越大越稳、越慢跟上新版本）
    meanWeight: 8,
    // 怎么调：前奏数得很像、但头一次乐段变化的时间差超过几秒，就当成两首（比如同一个前奏的另一个版本）
    sectionSeconds: 6,
  }),
});
