// The internal channel's golden (docs/claude/2026-11-17-app-tools-split.md): everything the user's own Claude sees of
// electron/safety/agent-channel/app-tools.ts, recorded so a move or a refactor can prove nothing changed, and so a changed tier,
// dialog, description or answer shows up as a failing test (tests/app-tools-golden.test.ts):
//   catalog      the fixed catalog (tool names, titles, tiers, descriptions, input schemas), the settings, what is never exposed, the
//                tools that always open a dialog;
//   definitions  each tool as the registry sees it, in list order: name, title, tier, interconnectOnly / alwaysConfirm / touchesFiles,
//                which hooks it has (tierFor, alwaysConfirmFor, confirmation, load, wordsItem, …);
//   exposure     which tools exist with 三方互通 on and off, and their tiers;
//   behaviour    every tool on a fixed fake soft hearts (tests/helpers/app-tools-world.ts), each sample in each way it can be called:
//                the answer, the dialog text, the notice, the record (tier, approval, words length), every host operation, the undo;
//                read_handbook / list_settings / get_status … answers are here (the handbook text the user's Claude reads);
//   helpers      the module's exported helpers on fixed inputs and its exported texts;
//   surface      the module's export surface read with the type checker (scripts/dev/journal-surface.mjs moduleSurface).
//   node node_modules/tsx/dist/cli.mjs scripts/dev/app-tools-golden.ts            counts
//   node node_modules/tsx/dist/cli.mjs scripts/dev/app-tools-golden.ts --write    regenerate tests/fixtures/app-tools-golden.json
// Regenerate only for an intended change (a new tool, a new tier, new words), and say why in the commit.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { behaviourGolden, catalogGolden, definitionsGolden, exposureGolden, helpersGolden } from '../../tests/helpers/app-tools-world';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
export const GOLDEN_FILE = 'tests/fixtures/app-tools-golden.json';
export const MODULE = 'electron/safety/agent-channel/app-tools.ts';

export async function surfaceGolden(root = ROOT): Promise<unknown> {
  const { moduleSurface } = await import(pathToFileURL(path.join(root, 'scripts/dev/journal-surface.mjs')).href) as { moduleSurface(rel: string, root: string): unknown };
  return moduleSurface(MODULE, root);
}

export async function buildGolden(root = ROOT): Promise<Record<string, unknown>> {
  return {
    note: 'Generated by `node node_modules/tsx/dist/cli.mjs scripts/dev/app-tools-golden.ts --write` (docs/claude/2026-11-17-app-tools-split.md); tests/app-tools-golden.test.ts compares. What the user\'s Claude sees of the internal channel: regenerate only for an intended change and say why in the commit.',
    catalog: catalogGolden(), definitions: definitionsGolden(), exposure: exposureGolden(), helpers: helpersGolden(),
    behaviour: await behaviourGolden(), surface: await surfaceGolden(root),
  };
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const golden = await buildGolden();
  const text = JSON.stringify(golden, null, 1) + '\n';
  if (process.argv.includes('--write')) { fs.writeFileSync(path.join(ROOT, GOLDEN_FILE), text); console.log(`written ${GOLDEN_FILE} (${Math.round(text.length / 1024)} KB)`); }
  else {
    const behaviour = golden.behaviour as Record<string, Record<string, Record<string, unknown>>>;
    const calls = Object.values(behaviour).reduce((sum, rows) => sum + Object.values(rows).reduce((n, runs) => n + Object.keys(runs).length, 0), 0);
    console.log(JSON.stringify({ tools: (golden.definitions as unknown[]).length, samples: Object.values(behaviour).reduce((n, rows) => n + Object.keys(rows).length, 0),
      calls, surfaceExports: Object.keys(golden.surface as object).length, kb: Math.round(text.length / 1024) }));
  }
}
