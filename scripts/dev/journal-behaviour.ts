// The experience journal's behaviour golden (docs/claude/2026-11-16-journal-split.md, step 0): what shared/memory/journal.ts does
// with every input tests/helpers/journal-behaviour.ts makes (the line written or refused, the panel text, the line read back),
// the closed lists it exports, and its helpers. tests/journal-behaviour.test.ts recomputes it and compares.
//   node node_modules/tsx/dist/cli.mjs scripts/dev/journal-behaviour.ts            print counts
//   node node_modules/tsx/dist/cli.mjs scripts/dev/journal-behaviour.ts --write    regenerate tests/fixtures/journal-behaviour.json
// Regenerate only for an intended change (a new journal entry type, a new word, a new field) and say why in the commit.
process.env.TZ = 'UTC';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as journal from '../../shared/memory/journal';
import { examples, exportedData, helperCases, lineCases, sweep, AT, type JournalApi } from '../../tests/helpers/journal-behaviour';
import { journalPools } from './journal-pools.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
export const BEHAVIOUR_FILE = 'tests/fixtures/journal-behaviour.json';

const api = journal as unknown as JournalApi;
const pools = journalPools(ROOT);
const types = journal.JOURNAL_TYPES;
const golden = {
  note: 'Generated by `node node_modules/tsx/dist/cli.mjs scripts/dev/journal-behaviour.ts --write` (docs/claude/2026-11-16-journal-split.md); tests/journal-behaviour.test.ts compares. Every input is made up in tests/helpers/journal-behaviour.ts; none comes from a real journal. Regenerate only for an intended change and say why in the commit.',
  at: AT,
  data: exportedData(journal as unknown as Record<string, unknown>),
  pools,
  examples: Object.fromEntries(types.map(type => [type, examples(api, type)])),
  sweep: Object.fromEntries(types.map(type => [type, sweep(api, type, pools)])),
  lines: lineCases(api),
  helpers: helperCases(api),
};

const total = Object.values(golden.sweep).reduce((sum, s) => sum + s.cases, 0);
const accepted = Object.values(golden.sweep).reduce((sum, s) => sum + s.accepted, 0);
if (process.argv.includes('--write')) {
  fs.writeFileSync(path.join(ROOT, BEHAVIOUR_FILE), JSON.stringify(golden, null, 1) + '\n');
  console.log(`written ${BEHAVIOUR_FILE}: ${types.length} types, ${total} cases, ${accepted} accepted`);
} else console.log(`${types.length} types, ${total} cases, ${accepted} accepted`);
