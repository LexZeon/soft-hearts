async function init(): Promise<void> {
  // Subscribe before the startup awaits; the handler attaches further down (src/stage/latched-signal.ts).
  const petRecovered = latchSignal(callback => window.desktop.onPetRecovered(callback));
  const interfaceLanguage = await window.desktop.getUiLanguage();
  setUiLanguage(interfaceLanguage.language);
  document.documentElement.lang = interfaceLanguage.language;
  await loadSettings();
  wireTtsBudget();
  wirePetVisibilityIntent();
  if (isPet) mountPetWindow();
  else mountControlWindow(interfaceLanguage);
  mountImmersiveNotice();
  wireAgentNotices();
  mountUserProfile();
  wireModelCapabilities();
  createStage();
  startHerStateReports();
  showHostVisibility();
  wirePetPointerAndFraming();
  await initModelPhysicsSettings();
  await initMusicSettings();
  await startMoodCompanion();
  wireInputGates();
  await mountMemoryPanels();
  wireChatReset();
  wireAmbientComments();
  wireProactiveInput();
  wirePetRecovery(petRecovered);
  createMotionPreview();
  applyStage();
  warmAudioOutput(); // after the model load has begun: the stall overlaps loading instead of her first words
  updateSummary();
  await mountControlTools();
  wireSettingsUpdates();
  wireChatStream();
  wireReplyExtras();
  await wireVision();
  wireTextMemorial();
  mountPetOverlays();
  await mountProactiveOffer();
  wireChatTyping();
  await startVoiceInput();
  await wireRuntimeState();
  wireCharacterCards();
  await mountCharacterTools();
  await wireBlushCalibration();
  applyCharacterCards(await window.desktop.getCharacterCards());
  connectChatChannel();
  startPointerFollow();
  wireDocumentVisibility();
  wireUnload();
}
window.desktop.onWindowVisibility(acceptWindowVisibility);
void window.desktop.getWindowVisibility().then(acceptWindowVisibility).catch(error => notify(String(error), true));
void init().then(() => { if (isPet) void checkPetPresentation({ document, hostVisible: () => hostVisible, reason: 'startup', delayMs: 3000,
  report: sample => window.desktop.reportPetPresentation(sample) }); }).catch((error) => {
  showStartupFailure(error);
  console.error(error);
});
