/**
 * 功能：她开口前先叫醒耳机（I-150）
 *
 * 旋钮文件：能调的值都在这里。每个旋钮上面一行"用户可能怎么说"，下面可选一行"怎么调"；
 * handbook/knobs.md 那张"想改什么 → 改哪里"的表由 `node scripts/list-knobs.mjs` 从这些行生成，别手改那张表。
 *
 * 读法：
 *  - 网页声音静了约 30 秒，浏览器就把真正的输出流停掉；蓝牙耳机（用户的 AirPods Pro）跟着睡下，下一句开头进来时要先醒，
 *    醒的那一截就被吃掉了。所以快要说话时（你发出消息、她要开口、试听），先在这个窗口的声音输出上放一段听不见的极小信号，
 *    把输出和耳机叫醒；她说话时一直放着，最后一个声音之后再留 KEEP_AFTER_MS，然后放手。
 *  - 冷着（最近 WAKE_COLD_AFTER_MS 里没有声音也没有叫醒信号）且她的第一个声音离叫醒开始不到 WAKE_LEAD_MS 时，
 *    第一个声音等到满 WAKE_LEAD_MS 再出；热着从不多等。你发消息到她出声本来就有约 2 秒，平时不多等。
 *  - 叫醒信号从不算"她在说话"：嘴、口型音量、气泡、说话保持都看不到它。朗读关着或音量为 0 时完全不叫醒。
 *  - 代价：信号放着时浏览器不会停掉输出流，电脑在那段时间里不会因为"没有声音"而进入睡眠；所以只在说话前后放，
 *    最多留 KEEP_AFTER_MS，从不一直放。
 * 这些都只是试用值，没在用户的耳机上听过。
 */

// 用户可能怎么说：朗读开头还是被吃掉一两个字／她自己开口时第一个字还是没有
// 怎么调：冷着时，她的第一个声音至少等叫醒信号开始后多少毫秒才出（大一点更不容易吃字，她自己开口时出声更晚；你发消息后的回复一般不受影响）
export const WAKE_LEAD_MS = 800;
// 用户可能怎么说：她说完以后电脑很久才睡／连着说两句时第二句开头被吃
// 怎么调：她最后一个声音之后，叫醒信号再放多少毫秒才停（停了以后浏览器约 30 秒后才会停掉输出流）；从不一直放
export const KEEP_AFTER_MS = 20_000;
// 怎么调：多久没有声音也没有叫醒信号，就当输出已经冷了（浏览器约 30 秒后停掉输出流；这里取得稍短，宁可多等一下）
export const WAKE_COLD_AFTER_MS = 25_000;
// 用户可能怎么说：戴着耳机安静的时候能听到一点嗡嗡声
// 怎么调：叫醒信号的大小（满幅是 1；0.0005 约 −66 dBFS，远低于听得见的大小，只要不是 0 浏览器就不会把它当静音）
export const WAKE_LEVEL = 0.0005;
// 怎么调：叫醒信号的频率（赫兹）；很低的频率在这个大小下听不见
export const WAKE_TONE_HZ = 30;
// 怎么调：叫醒信号淡入、淡出用多少毫秒（避免开关时"咔"一声）
export const WAKE_RAMP_MS = 60;
